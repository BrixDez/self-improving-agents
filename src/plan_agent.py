"""
plan_agent.py — Plan role for self-improving agent system.
==========================================================

DESIGN:
  - Takes Review's accepted recommendations (with scores) as input
  - Transforms recommendations into concrete, actionable proposals
  - Proposals are: change_type, summary, description, priority, estimated_effort
  - Priority derived from: recommendation priority + scores (novelty, relevance, etc.)
  - All proposals written to change board as change_type="proposal"
  - Fail-closed: if no valid recommendations, raises before proposing

CONTRACT:
  Input: PipelineContext with review_recommendations (list of Recommendation objects)
  Output: list of Proposal objects for the pipeline context
  
  Each Proposal becomes a change board entry that Code role can consume.

KEDB considerations:
  - Model may invent proposal types -> constrain at parser boundary
  - Model may over/under-estimate effort -> use conservative defaults
  - Empty input -> fail-closed (no proposals generated)
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from backbone import Backbone
    from pipeline import PipelineContext


# ---------------------------------------------------------------- constants

# Valid proposal types (constrain at parser boundary)
PROPOSAL_TYPES = (
    "feature",           # New functionality
    "bugfix",            # Fixes a defect
    "refactor",          # Code restructuring without behavior change
    "test",              # New or improved tests
    "docs",              # Documentation improvements
    "infrastructure",    # Build, CI, deployment improvements
    "research",          # Exploratory work, spikes
)

# Default effort estimates (in arbitrary units, e.g., hours or story points)
EFFORT_DEFAULT = 5
EFFORT_RANGE = {
    "low": 2,
    "medium": 5,
    "high": 8,
}

# Priority calculation weights
SCORE_WEIGHTS = {
    "novelty": 0.3,
    "relevance": 0.3,
    "evidence_quality": 0.2,
    "actionability": 0.15,
    "vision_alignment": 0.05,
}


@dataclass
class Proposal:
    """A concrete proposal generated by the Plan role."""
    # What to change
    change_type: str
    summary: str
    description: str
    
    # Why (from Review recommendation)
    source: str
    evidence: str
    impact: str
    risk: str
    recommendation_type: str  # original review type
    
    # Priority and effort
    priority: float
    estimated_effort: int
    
    # Metadata
    recommendation_id: str | None = None  # reference to source recommendation
    model_proposal_type: str = ""  # original type word from model (pre-normalisation)
    scores: dict = field(default_factory=dict)  # inherited from recommendation
    
    # For change board
    def to_change_payload(self) -> dict:
        """Convert to payload format for change board."""
        return {
            "change_type": self.change_type,
            "summary": self.summary,
            "description": self.description,
            "source": self.source,
            "evidence": self.evidence,
            "impact": self.impact,
            "risk": self.risk,
            "recommendation_type": self.recommendation_type,
            "priority": self.priority,
            "estimated_effort": self.estimated_effort,
            "scores": self.scores,
            "model_proposal_type": self.model_proposal_type,
        }


