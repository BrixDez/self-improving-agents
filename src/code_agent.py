"""
code_agent.py — Code role for self-improving agent system.
========================================================

DESIGN:
  - Takes accepted proposals from Plan role as input
  - Generates code patches/diffs (deterministic for now, no LLM)
  - Does NOT apply code directly - Test role validates first
  - All code changes written to change board as change_type="code_change"
  - Fail-closed: invalid input or generation failures abort the pipeline

CONTRACT:
  Input: PipelineContext with plan_proposals
  Output: list of CodeChange objects for the pipeline context
  
  Each CodeChange becomes a change board entry that Test role can consume.

KEDB considerations:
  - Model may fabricate code -> constrain at parser boundary (future)
  - Empty input -> fail-closed (no code to generate)
  - Code never applied directly (AGENTS.md implicit: changes flow through board)
"""

